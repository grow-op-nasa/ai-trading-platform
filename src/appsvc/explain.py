def cycle(status: str, reason_code: str | None = None) -> Explanation:
    base = _CYCLE.get(status, Explanation(f"Unrecognised cycle status {status!r}; shown exactly as stored.", "", "WARN"))
    extra = _REASON.get(reason_code or "")
    return Explanation(base.meaning + (f" ({extra})" if extra and extra not in base.meaning else ""), base.next_step, base.kind)


def reason(code: str | None) -> str:
    return _REASON.get(code or "", f"Reason code {code} (no description recorded)." if code else "")


def check(status: str) -> Explanation:
    return _CHECK.get(status, Explanation(f"Unrecognised check status {status!r}.", "", "WARN"))


def proposal(status: str) -> Explanation:
    return _PROPOSAL.get(status, Explanation(f"Unrecognised proposal status {status!r}.", "", "WARN"))


def freshness(state: str) -> Explanation:
    return _FRESHNESS.get(state, Explanation(f"Unrecognised freshness state {state!r}.", "", "WARN"))


def reconciliation(status: str) -> Explanation:
    return {
        "MATCH": Explanation("The portfolio matches the paper broker's ledger.", "", "OK"),
        "PENDING": Explanation("Unresolved intents exist, so values may legitimately lag until they resolve.", "Let the next run resolve them.", "WARN"),
        "MISMATCH": Explanation("The recorded portfolio state differs from the paper broker's available records. New risk-taking is blocked until the discrepancy is understood.",
                                "Review the discrepancy on Portfolio & Execution. There is no automatic repair.", "FAIL"),
    }.get(status, Explanation(f"Unrecognised reconciliation status {status!r}.", "", "WARN"))
