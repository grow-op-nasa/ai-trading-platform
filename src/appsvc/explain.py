"""Plain-English meaning of canonical statuses (Sprint 20). Deterministic lookup tables only.

The machine status is always kept and shown by the caller; these helpers add a short, evidence-free *meaning* and, when
the underlying condition supports one, a next safe step. Nothing here is generated by a model, nothing is inferred
from other records, and an unknown code is reported as unknown rather than invented. A "next step" never executes
anything and never offers a risk override or an automatic repair trade.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Explanation:
    meaning: str
    next_step: str = ""
    kind: str = "INFO"          # OK | INFO | WARN | FAIL (presentation hint only)


