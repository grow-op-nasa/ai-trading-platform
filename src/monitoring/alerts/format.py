"""Deterministic plain-text alert rendering -- src/monitoring/alerts/format.py (ADR-0052).

Pure function of (event, config): no LLM, no clock, no I/O, no network. Only facts frozen on
the event at its transition are used. No fabricated links. No credentials, no raw payloads.
"""

from __future__ import annotations

import json
import re
from typing import Any

from src.monitoring.alerts.config import AlertConfig
from src.monitoring.alerts.models import AlertEvent, AlertEventType, AlertMessage

_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
FOOTER = (
    "This is an informational notification generated by the deterministic monitoring rules. "
    "It does not recommend, place or change any trade, order, position or risk setting."
)


def clean_line(text: Any, limit: int = 300) -> str:
    """Single-line, control-character-free, bounded text (safe for headers and bodies)."""
    s = str(text).replace("\r", " ").replace("\n", " ")
    s = _CTRL.sub("", s).strip()
    return s if len(s) <= limit else s[: limit - 1] + "…"


def _val(v: Any) -> str:
    try:
        return clean_line(json.dumps(v, default=str, sort_keys=True), 200)
    except (TypeError, ValueError):
        return clean_line(v, 200)


def _what_changed(e: AlertEvent) -> str:
    if e.event_type == AlertEventType.NEW:
        if e.reason == "existing_at_enablement":
            return ("This finding was already open when alerting was enabled "
                    "(policy: notify about existing findings).")
        return "A new finding was opened by the monitoring rules."
    if e.event_type == AlertEventType.ESCALATED:
        prev = e.previous_severity.value if e.previous_severity else "?"
        return f"The finding's severity rose from {prev} to {e.severity.value}."
    return ("The finding was resolved under the monitoring rules: the rule was re-evaluated on valid "
            "evidence and the condition is no longer detected. This does not mean the portfolio or "
            "market data is otherwise healthy.")


def subject_for(e: AlertEvent, config: AlertConfig) -> str:
    env = f" {config.environment_label}" if config.environment_label else ""
    sev = e.severity.value if e.event_type != AlertEventType.RESOLVED else "was " + e.severity.value
    return clean_line(f"[{config.subject_prefix}{env}] {e.event_type.value} ({sev}): {e.title}", 200)


def render_message(event: AlertEvent, config: AlertConfig) -> AlertMessage:
    s = event.snapshot
    src = s.get("source", {}) or {}
    scope = f"{clean_line(src.get('source'))}, experiment_id={clean_line(src.get('experiment_id'))}"
    if s.get("is_paper_snapshot"):
        scope += " (stored paper-portfolio snapshot, not a live trading session)"
    lines = [
        f"Monitoring alert: {event.event_type.value} ({event.severity.value})",
    ]
    if config.environment_label:
        lines.append(f"Environment: {clean_line(config.environment_label)}")
    lines += [
        "",
        f"What changed: {_what_changed(event)}",
        "",
        f"Finding:      {clean_line(event.title)}",
        f"Rule:         {clean_line(event.rule_id)} (category: {clean_line(s.get('category'))})",
        f"Finding ID:   {clean_line(event.finding_id)}",
        f"Fingerprint:  {clean_line(event.fingerprint)}",
        f"Severity:     {event.severity.value}"
        + (f" (previously {event.previous_severity.value})" if event.previous_severity else ""),
        f"Status:       {event.finding_status.value}",
        f"First seen (UTC):          {clean_line(s.get('first_seen'))}",
        f"Transition recorded (UTC): {event.occurred_at.strftime('%Y-%m-%dT%H:%M:%SZ')}",
        f"Monitoring run: {clean_line(event.run_id)}",
        f"Scope: {scope}",
        "",
        f"Summary: {clean_line(s.get('description'), 500)}",
        f"Observed: {_val(s.get('observed_value'))}",
        f"Expected: {_val(s.get('expected_value'))}",
    ]
    ev = s.get("evidence") or []
    if ev:
        lines.append("Evidence:")
        for item in ev[:5]:
            lines.append(f"  - {clean_line(item.get('reference'))}: {clean_line(item.get('summary'), 200)}")
    lines += ["", f"Alert event ID: {event.event_id}", "", FOOTER, ""]
    return AlertMessage(subject=subject_for(event, config), body="\n".join(lines), event_id=event.event_id)


def render_test_message(config: AlertConfig, recipient: str, event_id: str) -> AlertMessage:
    env = f" {config.environment_label}" if config.environment_label else ""
    body = (
        "ATP alert delivery TEST\n\n"
        "This message was sent because an operator ran `alerts test-send` with explicit confirmation.\n"
        "It is NOT a monitoring finding and corresponds to no event in the alert outbox.\n\n"
        f"Test event ID: {event_id}\n\n{FOOTER}\n"
    )
    return AlertMessage(subject=clean_line(f"[{config.subject_prefix}{env}] TEST message", 200), body=body,
                        event_id=event_id, recipients=(recipient,), is_test=True)
